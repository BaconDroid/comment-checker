#[test]
fn cli_keyword_acquit_never_reports_rationale_comment() -> std::io::Result<()> {
    // given: a rationale comment the default fallback spares
    let input = r##"{"tool_name":"Write","tool_input":{"file_path":"test.py","content":"# because the retry budget is finite\nx = 1\n"}}"##;

    // when
    let output = run_checker_with_keyword_acquit(input, &[], Some("never"))?;

    // then: strict mode reports its text-level reason instead of acquitting the prose
    assert_eq!(output.status.code(), Some(2));
    assert!(
        String::from_utf8_lossy(&output.stderr).contains("reason=\"unnecessary-comment\""),
        "stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(())
}

#[test]
fn cli_keyword_acquit_never_keeps_structural_justifications() -> std::io::Result<()> {
    // given: one comment per structural justification
    let cases = [
        "# SPDX-License-Identifier: MIT\nx = 1\n",
        "# Code generated by protoc. DO NOT EDIT.\nx = 1\n",
        "# adapted from upstream\nx = 1\n",
        "\"\"\"@param x the value\"\"\"\nx = 1\n",
    ];

    // when / then
    for content in cases {
        let input = serde_json::json!({
            "tool_name": "Write",
            "tool_input": {"file_path": "test.py", "content": content},
        })
        .to_string();
        let output = run_checker_with_keyword_acquit(&input, &[], Some("never"))?;
        assert!(output.status.success(), "content: {content}");
    }
    Ok(())
}

