use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};

fn run_checker(input: &str, args: &[&str]) -> std::io::Result<std::process::Output> {
    run_checker_with_keyword_acquit(input, args, None)
}

fn run_checker_with_keyword_acquit(
    input: &str,
    args: &[&str],
    keyword_acquit: Option<&str>,
) -> std::io::Result<std::process::Output> {
    let mut command = Command::new(env!("CARGO_BIN_EXE_comment-checker"));
    command
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    match keyword_acquit {
        Some(value) => command.env("COMMENT_CHECKER_KEYWORD_ACQUIT", value),
        None => command.env_remove("COMMENT_CHECKER_KEYWORD_ACQUIT"),
    };
    let mut child = command.spawn()?;
    let Some(stdin) = child.stdin.as_mut() else {
        return Err(std::io::Error::other("checker stdin unavailable"));
    };
    stdin.write_all(input.as_bytes())?;
    child.wait_with_output()
}

/// A per-test scratch directory, removed on drop.
struct TempDir(PathBuf);

impl TempDir {
    fn new(label: &str) -> std::io::Result<Self> {
        static COUNTER: AtomicUsize = AtomicUsize::new(0);
        let unique = COUNTER.fetch_add(1, Ordering::Relaxed);
        let path = std::env::temp_dir().join(format!(
            "comment-checker-strip-{}-{label}-{unique}",
            std::process::id()
        ));
        std::fs::create_dir_all(&path)?;
        Ok(Self(path))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn strip_payload(file_path: &str, cwd: &Path) -> String {
    serde_json::json!({
        "tool_name": "Write",
        "tool_input": { "file_path": file_path },
        "cwd": cwd,
    })
    .to_string()
}

#[test]
fn cli_given_no_comment_exits_zero() -> std::io::Result<()> {
    // given
    let input =
        r#"{"tool_name":"Write","tool_input":{"file_path":"test.py","content":"print(1)"}}"#;

    // when
    let output = run_checker(input, &[])?;

    // then
    assert!(output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("Success"));
    Ok(())
}

