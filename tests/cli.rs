#[test]
fn cli_keyword_acquit_is_read_per_invocation() -> std::io::Result<()> {
    // given: the same payload, checked by separate processes with different modes
    let input = r##"{"tool_name":"Write","tool_input":{"file_path":"test.py","content":"# because the retry budget is finite\nx = 1\n"}}"##;

    // when
    let strict = run_checker_with_keyword_acquit(input, &[], Some("never"))?;
    let proven_only = run_checker_with_keyword_acquit(input, &[], Some("proven-only"))?;
    let missing = run_checker_with_keyword_acquit(input, &[], None)?;

    // then: no invocation inherits another's mode
    assert_eq!(strict.status.code(), Some(2));
    assert!(proven_only.status.success());
    assert!(missing.status.success());
    Ok(())
}

